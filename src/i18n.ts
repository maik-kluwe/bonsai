/** English when there is no VS Code (the flows run in plain Node in the tests). */
const language = (): string => {
  try { return (require('vscode') as typeof import('vscode')).env.language; } catch { return 'en'; }
};

export const lang: 'de' | 'en' = language().toLowerCase().startsWith('de') ? 'de' : 'en';
export const strings: Strings = lang === 'de' ? de : en;

export function t(key: keyof Strings, ...args: (string | number)[]): string {
  return strings[key].replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}
